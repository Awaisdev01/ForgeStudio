const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('gateway', {
  getState: () => ipcRenderer.invoke('gw:getState'),
  saveConfig: (patch) => ipcRenderer.invoke('gw:saveConfig', patch),
  mintToken: (plan) => ipcRenderer.invoke('gw:mintToken', plan),
  testUpstream: () => ipcRenderer.invoke('gw:testUpstream'),
});

contextBridge.exposeInMainWorld('studio', {
  getModels: () => ipcRenderer.invoke('studio:getModels'),
  getProviders: () => ipcRenderer.invoke('studio:getProviders'),
  setProviderKey: (provider, key) => ipcRenderer.invoke('studio:setProviderKey', { provider, key }),
  listSessions: () => ipcRenderer.invoke('studio:listSessions'),
  resumeSession: (id) => ipcRenderer.invoke('studio:resumeSession', id),
  applyDiff: (d) => ipcRenderer.invoke('studio:applyDiff', d),
  runAgent: (args) => ipcRenderer.invoke('studio:runAgent', args),
  listMcp: () => ipcRenderer.invoke('studio:listMcp'),
  addMcp: (e) => ipcRenderer.invoke('studio:addMcp', e),
  removeMcp: (i) => ipcRenderer.invoke('studio:removeMcp', i),
  pickFolder: () => ipcRenderer.invoke('studio:pickFolder'),
  fileTree: (dir) => ipcRenderer.invoke('studio:fileTree', dir),
  readFile: (abs) => ipcRenderer.invoke('studio:readFile', abs),
  scanLocal: () => ipcRenderer.invoke('studio:scanLocal'),
  testProvider: (pid) => ipcRenderer.invoke('studio:testProvider', pid),
  getSettings: () => ipcRenderer.invoke('studio:getSettings'),
  setSettings: (patch) => ipcRenderer.invoke('studio:setSettings', patch),
  listDir: (dir) => ipcRenderer.invoke('studio:listDir', dir),
  grep: (pattern) => ipcRenderer.invoke('studio:grep', pattern),
  gitInfo: (ws) => ipcRenderer.invoke('studio:gitInfo', ws),
  gitUndo: (ws) => ipcRenderer.invoke('studio:gitUndo', ws),
  gitCommit: (ws, msg) => ipcRenderer.invoke('studio:gitCommit', { ws, msg }),
  createThreadBranch: (sessionId, ws) => ipcRenderer.invoke('studio:createThreadBranch', { sessionId, ws }),
  mergeThreadBranch: (sessionId, ws) => ipcRenderer.invoke('studio:mergeThreadBranch', { sessionId, ws }),
  discardThreadBranch: (sessionId, ws) => ipcRenderer.invoke('studio:discardThreadBranch', { sessionId, ws }),
  getRules: (ws) => ipcRenderer.invoke('studio:getRules', ws),
  setRules: (ws, content) => ipcRenderer.invoke('studio:setRules', { ws, content }),
  saveImage: (dataUrl, name) => ipcRenderer.invoke('studio:saveImage', { dataUrl, name }),
  runVerify: (ws) => ipcRenderer.invoke('studio:runVerify', ws),
  listRecent: () => ipcRenderer.invoke('studio:listRecent'),
  pushRecent: (ws) => ipcRenderer.invoke('studio:pushRecent', ws),
  previewStart: (ws) => ipcRenderer.invoke('studio:previewStart', ws),
  previewStop: () => ipcRenderer.invoke('studio:previewStop'),
  renameSession: (id, title) => ipcRenderer.invoke('studio:renameSession', { id, title }),
  deleteSession: (id) => ipcRenderer.invoke('studio:deleteSession', id),
  undoCheckpoint: () => ipcRenderer.invoke('studio:undoCheckpoint'),
  stopAgent: (id) => ipcRenderer.invoke('studio:stopAgent', id),
  listCheckpoints: () => ipcRenderer.invoke('studio:listCheckpoints'),
  restoreCheckpoint: (id) => ipcRenderer.invoke('studio:restoreCheckpoint', id),
  exportSession: (id) => ipcRenderer.invoke('studio:exportSession', id),
  applyDiffs: (diffs) => ipcRenderer.invoke('studio:applyDiffs', diffs),
  onUsage: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'usage') cb(d.payload); }),
  onThinking: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'thinking-delta') cb(d.payload); }),
  onAgentEvent: (cb) => ipcRenderer.on('studio:agent-event', (_e, data) => cb(data)),
  // fine-grained event aliases over the single studio:agent-event channel
  onToken: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'text-delta') cb(d.payload); }),
  onToolEvent: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'tool-start' || d?.type === 'tool-end') cb(d); }),
  onDiffUpdate: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'diff') cb(d.payload); }),
  onDone: (cb) => ipcRenderer.on('studio:agent-event', (_e, d) => { if (d?.type === 'done') cb(d.payload); }),
});
